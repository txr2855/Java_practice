package com.jialidun.branch;

public class SwitchDome4 {
    //我学switch
    public static void main(String[] args) {
        print(1);

    }
    public static void print(int a){
        switch (a){
            case 1:
                System.out.println("1");
                break;
            case 2:
                System.out.println("2");
                break;
            case 3:
                System.out.println("3");
                break;
            default:
                System.out.println("其他");
        }
    }
}
